#!/usr/bin/env python3
"""Generate firmware assets for the HIDDENMACHINE receiver (ESP32-2432S028R).

Reads the station source (HiddenMachine.dc.html) and the IBM Plex Mono TTFs
(laser/tools/fonts/) and emits into receiver/src/:

  phrases.h    - MESSAGES pool, INBOUND fragments, scramble GLYPHS (PROGMEM)
  hm_colors.h  - site oklch palette converted to RGB565
  hm_fonts.h   - VLW smooth fonts (TFT_eSPI loadFont format) as PROGMEM arrays

Re-run after every pool change, then rebuild the firmware:
  python3 receiver/tools/gen_assets.py && pio run -d receiver
"""
import math, os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(HERE, "..", "src")
DC = os.path.join(ROOT, "HiddenMachine.dc.html")
FONTDIR = os.path.join(ROOT, "laser", "tools", "fonts")

# ---------------------------------------------------------------- phrases --
html = open(DC, encoding="utf-8").read()

def parse_entries(blob):
    return re.findall(r'\{ motif:"([^"]+)", text:"((?:[^"\\]|\\.)*)" \}', blob)

mblock = re.search(r'const MESSAGES = \[(.*?)\n\];', html, re.S).group(1)
MESSAGES = parse_entries(mblock)
iblock = re.search(r'const INBOUND = \[(.*?)\n\];', html, re.S).group(1)
INBOUND = re.findall(r'"((?:[^"\\]|\\.)*)"', iblock)
GLYPHS = re.search(r'const GLYPHS = "((?:[^"\\]|\\.)*)";', html).group(1)

def junescape(s):
    return re.sub(r'\\u([0-9a-fA-F]{4})', lambda m: chr(int(m.group(1), 16)),
                  s.replace('\\"', '"').replace("\\\\", "\\"))

MESSAGES = [(m, junescape(t)) for m, t in MESSAGES]
INBOUND = [junescape(s) for s in INBOUND]
GLYPHS = junescape(GLYPHS)
assert len(MESSAGES) > 200, "MESSAGES parse failed"

def cesc(s):
    out = []
    for ch in s:
        if ch == '"': out.append('\\"')
        elif ch == "\\": out.append("\\\\")
        elif ord(ch) < 128: out.append(ch)
        else: out.append("".join("\\x%02x" % b for b in ch.encode("utf-8")))
    # avoid hex-escape swallowing a following hex digit
    return re.sub(r'(\\x[0-9a-f]{2})([0-9a-fA-F])', r'\1""\2', "".join(out))

with open(os.path.join(SRC, "phrases.h"), "w") as f:
    f.write("// Generated by tools/gen_assets.py - do not edit.\n")
    f.write("#pragma once\n#include <pgmspace.h>\n\n")
    f.write("struct HmMessage { const char* motif; const char* text; };\n\n")
    for i, (m, t) in enumerate(MESSAGES):
        f.write('static const char HM_T%d[] PROGMEM = "%s";\n' % (i, cesc(t)))
    f.write("\nstatic const HmMessage MESSAGES[] PROGMEM = {\n")
    for i, (m, t) in enumerate(MESSAGES):
        f.write('  { "%s", HM_T%d },\n' % (m, i))
    f.write("};\n")
    f.write("static const int MESSAGE_COUNT = %d;\n\n" % len(MESSAGES))
    for i, s in enumerate(INBOUND):
        f.write('static const char HM_I%d[] PROGMEM = "%s";\n' % (i, cesc(s)))
    f.write("\nstatic const char* const INBOUND[] PROGMEM = {\n")
    for i in range(len(INBOUND)):
        f.write("  HM_I%d,\n" % i)
    f.write("};\n")
    f.write("static const int INBOUND_COUNT = %d;\n\n" % len(INBOUND))
    f.write('static const char HM_GLYPHS[] PROGMEM = "%s";\n' % cesc(GLYPHS))
print("phrases.h: %d messages, %d inbound" % (len(MESSAGES), len(INBOUND)))

# ----------------------------------------------------------------- colors --
def oklch_to_rgb(L, C, H):
    h = math.radians(H)
    a, b = C * math.cos(h), C * math.sin(h)
    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_**3, m_**3, s_**3
    r = +4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    bb = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
    def gam(u):
        u = max(0.0, min(1.0, u))
        return 12.92 * u if u <= 0.0031308 else 1.055 * u ** (1 / 2.4) - 0.055
    return tuple(round(gam(v) * 255) for v in (r, g, bb))

def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)

def blend(fg, bg, alpha):
    return tuple(round(f * alpha + b * (1 - alpha)) for f, b in zip(fg, bg))

PAL = {
    "BG":        (0.13, 0.012, 250),   # flat ground (site: radial 0.115-0.185)
    "TEXT":      (0.92, 0.008, 235),   # resolved message
    "CYAN":      (0.74, 0.08, 205),    # accent / cursor / wave / out label
    "CYAN_DIM":  (0.72, 0.05, 205),    # motif value
    "AMBER":     (0.68, 0.09, 75),     # IN label
    "AMBER_DIM": (0.50, 0.03, 75),     # inbound text
    "GRAY66":    (0.66, 0.014, 245),   # clock
    "GRAY56":    (0.56, 0.014, 245),   # header text
    "GRAY50":    (0.50, 0.014, 245),   # meta row
    "GRAY44":    (0.44, 0.012, 245),   # station id
    "GRAY40":    (0.40, 0.012, 245),   # footer
    "GRID":      (0.30, 0.012, 245),   # rules / wave midline
}
rgb = {k: oklch_to_rgb(*v) for k, v in PAL.items()}
rgb["SCRAMBLE"] = blend(rgb["CYAN"], rgb["BG"], 0.82)   # cyan @ .82 on bg
with open(os.path.join(SRC, "hm_colors.h"), "w") as f:
    f.write("// Generated by tools/gen_assets.py - do not edit.\n#pragma once\n\n")
    for k, v in rgb.items():
        f.write("#define HM_%-10s 0x%04X  // rgb(%d,%d,%d)\n"
                % (k, rgb565(*v), *v))
print("hm_colors.h:", ", ".join("%s=#%02x%02x%02x" % (k, *v) for k, v in rgb.items()))

# ------------------------------------------------------------------ fonts --
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

charset = set(chr(c) for c in range(32, 127))
for _, t in MESSAGES: charset |= set(t)
for s in INBOUND: charset |= set(s)
charset |= set(GLYPHS)
charset.discard("\n")

BLOCKS = {"░": 0.25, "▒": 0.5, "▓": 0.75}  # ░ ▒ ▓ dither fills

def build_vlw(ttf_path, size, chars):
    font = ImageFont.truetype(ttf_path, size)
    cmap = set()
    tt = TTFont(ttf_path)
    for table in tt["cmap"].tables:
        cmap |= set(table.cmap.keys())
    ascent, descent = font.getmetrics()
    adv = font.getlength("M")
    glyphs = []
    for ch in sorted(chars, key=ord):
        cp = ord(ch)
        if cp in cmap:
            x0, y0, x1, y1 = font.getbbox(ch)
            w, h = x1 - x0, y1 - y0
            bm = b""
            if w > 0 and h > 0:
                img = Image.new("L", (w, h), 0)
                ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
                bm = img.tobytes()
            else:
                w = h = 0
            glyphs.append((cp, h, w, round(font.getlength(ch)),
                           ascent - y0 if h else 0, x0 if h else 0, bm))
        elif ch == "Δ":  # not in Google-Fonts Plex Mono; draw it (cards do too)
            h = round(size * 0.68)
            w = round(adv)
            img = Image.new("L", (w, h), 0)
            t = max(1, round(size * 0.09))
            ImageDraw.Draw(img).polygon(
                [(w // 2, 0), (0, h - 1), (w - 1, h - 1)],
                outline=230, width=t)
            glyphs.append((ord(ch), h, w, round(adv), h, 0, img.tobytes()))
        elif ch in BLOCKS:
            w, h = round(adv), round(size * 0.92)
            img = Image.new("L", (w, h), 0)
            px = img.load()
            lvl = BLOCKS[ch]
            for y in range(h):
                for x in range(w):
                    if ((x + 2 * y) % 4) / 4.0 < lvl:
                        px[x, y] = 230
            glyphs.append((ord(ch), h, w, round(adv),
                           round(size * 0.78), 0, img.tobytes()))
        else:
            glyphs.append((cp, 0, 0, round(adv), 0, 0, b""))  # tofu -> blank
    out = struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent)
    for cp, h, w, ga, dy, dx, _ in glyphs:
        out += struct.pack(">7i", cp, h, w, ga, dy, dx, 0)
    for *_, bm in glyphs:
        out += bm
    return out

# message tiers all cap at 5 lines; advances round to whole px, so the
# useful ladder is 16/14/12/10/9 (13 and 11 waste size for the same columns).
# small tiers use Regular - Light hairlines die below ~12px on this panel.
FONTS = [
    ("FontL16", "IBMPlexMono-Light.ttf", 16),
    ("FontL14", "IBMPlexMono-Light.ttf", 14),
    ("FontL12", "IBMPlexMono-Light.ttf", 12),
    ("FontXL11", "IBMPlexMono-ExtraLight.ttf", 11),
    ("FontR10", "IBMPlexMono-Regular.ttf", 10),
    ("FontR9", "IBMPlexMono-Regular.ttf", 9),
]
with open(os.path.join(SRC, "hm_fonts.h"), "w") as f:
    f.write("// Generated by tools/gen_assets.py - do not edit.\n")
    f.write("#pragma once\n#include <pgmspace.h>\n\n")
    total = 0
    for name, ttf, size in FONTS:
        data = build_vlw(os.path.join(FONTDIR, ttf), size, charset)
        total += len(data)
        f.write("static const uint8_t %s[] PROGMEM = {\n" % name)
        for i in range(0, len(data), 24):
            f.write("  " + ",".join(str(b) for b in data[i:i+24]) + ",\n")
        f.write("};\n\n")
        print("%s: %s @ %dpx, %d glyphs, %d bytes"
              % (name, ttf, size, len(charset), len(data)))
    print("hm_fonts.h total: %d bytes" % total)
